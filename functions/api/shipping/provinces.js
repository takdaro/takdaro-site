export async function onRequestGet(context) {
  try {
    // دریافت استان از پارامتر (اختیاری)
    const url = new URL(context.request.url);
    const province = url.searchParams.get("province");

    if (province) {
      // اگر استان مشخص شده، لیست شهرهای آن را برگردان
      const cities = PROVINCES[province] || [];
      return json({
        success: true,
        province,
        cities
      });
    }

    // در غیر این صورت لیست کامل استان‌ها و شهرها را برگردان
    return json({
      success: true,
      provinces: PROVINCES,
      provinceList: Object.keys(PROVINCES)
    });
  } catch (error) {
    return json({
      success: false,
      error: String(error?.message || error)
    }, 500);
  }
}